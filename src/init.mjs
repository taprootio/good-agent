// @ts-check
/**
 * `good-agent init --skill [--force]`: install every shipped skill into
 * .agents/skills/<name>/ (Codex, Copilot) and .claude/skills/<name>/ (Claude
 * Code, Copilot) as generated copies. SKILL.md keeps `---` as its first line
 * (the Agent Skills format requires it); the first body line is a marker
 * naming the copy generated, giving the refresh command, and holding a hash
 * of the whole file with that line removed. Files under references/ are
 * hashed into .good-agent-manifest.json beside the installed SKILL.md. A
 * copy whose hash does not match was hand-edited: init refuses to overwrite
 * it (exit 2) unless --force. The source skills directory is a parameter so
 * tests can use a fixture skill.
 */
import { createHash } from "node:crypto";
import { existsSync, lstatSync, mkdirSync, readdirSync, readFileSync, rmSync, rmdirSync, writeFileSync, statSync } from "node:fs";
import { dirname, isAbsolute, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { parseFrontMatter } from "./markdown.mjs";

export const DEFAULT_SKILLS_DIR = join(dirname(fileURLToPath(import.meta.url)), "..", "skill");
export const INSTALL_DIRS = [".agents/skills", ".claude/skills"];
export const MANIFEST = ".good-agent-manifest.json";
const REFRESH = "npx good-agent init --skill";
const MARKER_RE = /^<!-- generated by good-agent init --skill; do not edit; refresh with: npx good-agent init --skill; sha256: ([0-9a-f]{64}) -->$/;

export class InitRefusal extends Error {}

/**
 * Line endings do not matter to a generated copy: a checkout with
 * core.autocrlf rewrites them, so everything is parsed, matched and hashed
 * with LF endings.
 * @param {string} text
 */
export function lf(text) {
  return text.replace(/\r\n/g, "\n");
}

/** @param {string} text */
export function sha256(text) {
  return createHash("sha256").update(lf(text)).digest("hex");
}

/**
 * The installed SKILL.md text: front matter, marker, body.
 * @param {string} source
 */
export function renderInstalledSkill(source) {
  source = lf(source);
  const fm = parseFrontMatter(source);
  if (!fm) throw new Error("SKILL.md must start with front matter");
  const head = source.slice(0, fm.bodyStart);
  const body = source.slice(fm.bodyStart);
  const hash = sha256(head + body);
  const marker = `<!-- generated by good-agent init --skill; do not edit; refresh with: ${REFRESH}; sha256: ${hash} -->`;
  return `${head}${marker}\n${body}`;
}

/**
 * Whether an installed SKILL.md is an unmodified generated copy. Returns
 * "ok", "missing-marker" or "edited".
 * @param {string} installed
 */
export function installedState(installed) {
  installed = lf(installed);
  const fm = parseFrontMatter(installed);
  if (!fm) return "missing-marker";
  const markerLine = installed.slice(fm.bodyStart).split("\n")[0] ?? "";
  const m = MARKER_RE.exec(markerLine);
  if (!m) return "missing-marker";
  const without = installed.slice(0, fm.bodyStart) + installed.slice(fm.bodyStart + markerLine.length + 1);
  return sha256(without) === m[1] ? "ok" : "edited";
}

/**
 * @param {string} dir
 * @returns {string[]} files under references/, relative to the skill dir, POSIX
 */
function referenceFiles(dir) {
  const refs = join(dir, "references");
  if (!existsSync(refs)) return [];
  /** @type {string[]} */
  const out = [];
  /** @param {string} d */
  const walk = (d) => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      const abs = join(d, e.name);
      if (e.isDirectory()) walk(abs);
      else if (e.isFile()) out.push(relative(dir, abs).split(sep).join("/"));
    }
  };
  walk(refs);
  return out.sort();
}

/**
 * @param {string} manifestPath
 * @returns {Record<string, string>}
 */
function readManifest(manifestPath) {
  if (!existsSync(manifestPath)) return {};
  try {
    const parsed = JSON.parse(readFileSync(manifestPath, "utf8"));
    if (parsed && typeof parsed === "object" && !Array.isArray(parsed)) return parsed;
  } catch { /* fall through */ }
  throw new InitRefusal(`${manifestPath} is not a valid good-agent manifest; re-run with --force to rewrite it`);
}

/**
 * @param {object} options
 * @param {string} options.root  the target repository
 * @param {string} [options.skillsDir]  the source skills directory
 * @param {boolean} [options.force]
 * @returns {{ installed: string[], unchanged: string[] }}
 */
export function installSkills({ root, skillsDir = DEFAULT_SKILLS_DIR, force = false }) {
  const names = readdirSync(skillsDir, { withFileTypes: true }).filter((e) => e.isDirectory() && existsSync(join(skillsDir, e.name, "SKILL.md"))).map((e) => e.name).sort();
  if (names.length === 0) throw new Error(`no skills found under ${skillsDir}`);
  /** @type {string[]} */
  const installed = [];
  /** @type {string[]} */
  const unchanged = [];
  // First pass: refuse before writing anything if any target was hand-edited.
  /** @type {{ target: string, skill: string, refs: Record<string, string>, orphans: string[] }[]} */
  const plan = [];
  for (const name of names) {
    const src = join(skillsDir, name);
    const skill = renderInstalledSkill(readFileSync(join(src, "SKILL.md"), "utf8"));
    /** @type {Record<string, string>} */
    const refs = {};
    for (const rel of referenceFiles(src)) refs[rel] = lf(readFileSync(join(src, ...rel.split("/")), "utf8"));
    for (const base of INSTALL_DIRS) {
      const target = join(root, ...base.split("/"), name);
      /** @type {string[]} */
      const orphans = [];
      preflightTarget(root, base, name, Object.keys(refs));
      if (existsSync(target)) {
        /** @type {Record<string, string>} */
        let manifest = {};
        try { manifest = readManifest(join(target, MANIFEST)); } catch (error) { if (!force) throw error; }
        // Installed reference files that are no longer shipped are removed
        // (a clean one, or any under --force; an edited one is refused below).
        for (const rel of Object.keys(manifest)) if (!(rel in refs) && safeRel(rel)) orphans.push(rel);
        // Preflight them before anything is read or compared.
        if (orphans.length > 0) preflightTarget(root, base, name, [...Object.keys(refs), ...orphans]);
        if (!force) checkTarget({ root, target, refs, manifest });
      }
      plan.push({ target, skill, refs, orphans });
    }
  }
  for (const item of plan) {
    mkdirSync(item.target, { recursive: true });
    const skillPath = join(item.target, "SKILL.md");
    const manifestPath = join(item.target, MANIFEST);
    /** @type {Record<string, string>} */
    const manifest = {};
    let changed = false;
    if (!existsSync(skillPath) || lf(readFileSync(skillPath, "utf8")) !== item.skill) { writeFileSync(skillPath, item.skill); changed = true; }
    for (const [rel, content] of Object.entries(item.refs)) {
      const file = join(item.target, ...rel.split("/"));
      mkdirSync(dirname(file), { recursive: true });
      if (!existsSync(file) || lf(readFileSync(file, "utf8")) !== content) { writeFileSync(file, content); changed = true; }
      manifest[rel] = sha256(content);
    }
    for (const rel of item.orphans) {
      const file = join(item.target, ...rel.split("/"));
      if (existsSync(file)) { rmSync(file); changed = true; pruneEmptyDirs(dirname(file), item.target); }
    }
    if (Object.keys(manifest).length === 0) {
      if (existsSync(manifestPath)) { rmSync(manifestPath); changed = true; }
    } else {
      const manifestText = `${JSON.stringify(manifest, null, 2)}\n`;
      if (!existsSync(manifestPath) || lf(readFileSync(manifestPath, "utf8")) !== manifestText) { writeFileSync(manifestPath, manifestText); changed = true; }
    }
    (changed ? installed : unchanged).push(relative(root, item.target).split(sep).join("/"));
  }
  return { installed, unchanged };
}

/**
 * Check one destination path before anything is written: absent is fine; a
 * symlink is refused (a refresh would write through it, --force or not); a
 * path of the wrong type is refused.
 * @param {string} root
 * @param {string} abs
 * @param {"dir" | "file"} kind
 */
function preflightPath(root, abs, kind) {
  /** @type {import("node:fs").Stats} */
  let st;
  try { st = lstatSync(abs); } catch { return; }
  const shown = relative(root, abs).split(sep).join("/");
  if (st.isSymbolicLink()) throw new InitRefusal(`${shown} is a symbolic link; init will not write through it (remove it and re-run)`);
  if (kind === "dir" ? !st.isDirectory() : !st.isFile()) throw new InitRefusal(`${shown} exists and is not a ${kind === "dir" ? "directory" : "regular file"}; move it aside and re-run`);
}

/**
 * Preflight every destination one skill install touches: the skills root,
 * the skill directory, SKILL.md, the manifest, each reference file and its
 * parent directories.
 * @param {string} root
 * @param {string} base  an INSTALL_DIRS entry
 * @param {string} name
 * @param {string[]} refs  reference paths relative to the skill directory, POSIX
 */
function preflightTarget(root, base, name, refs) {
  const parts = base.split("/");
  for (let i = 1; i <= parts.length; i += 1) preflightPath(root, join(root, ...parts.slice(0, i)), "dir");
  const target = join(root, ...parts, name);
  preflightPath(root, target, "dir");
  preflightPath(root, join(target, "SKILL.md"), "file");
  preflightPath(root, join(target, MANIFEST), "file");
  for (const rel of refs) {
    const segs = rel.split("/");
    for (let i = 1; i < segs.length; i += 1) preflightPath(root, join(target, ...segs.slice(0, i)), "dir");
    preflightPath(root, join(target, ...segs), "file");
  }
}

/**
 * Whether a manifest key is a plain relative path that stays inside the skill.
 * @param {string} rel
 */
function safeRel(rel) {
  return rel !== "" && !isAbsolute(rel) && !rel.split("/").includes("..");
}

/**
 * @param {string} dir
 * @param {string} stop  the skill directory, never removed
 */
function pruneEmptyDirs(dir, stop) {
  while (dir !== stop && dir.startsWith(stop) && readdirSync(dir).length === 0) { rmdirSync(dir); dir = dirname(dir); }
}

/**
 * Refuse (InitRefusal) when anything under an existing target was hand-edited.
 * @param {{ root: string, target: string, refs: Record<string, string>, manifest: Record<string, string> }} args
 */
function checkTarget({ root, target, refs, manifest }) {
  const skillFile = join(target, "SKILL.md");
  if (existsSync(skillFile)) {
    const state = installedState(readFileSync(skillFile, "utf8"));
    if (state !== "ok") throw new InitRefusal(`${relative(root, skillFile)} was ${state === "edited" ? "hand-edited" : "not generated by good-agent (no marker)"}; keep your edits in the canonical file or a separate skill, or re-run with --force to overwrite it`);
  }
  const edited = (/** @type {string} */ rel) => new InitRefusal(`${relative(root, join(target, ...rel.split("/")))} was hand-edited; re-run with --force to overwrite it`);
  for (const [rel, content] of Object.entries(refs)) {
    const file = join(target, ...rel.split("/"));
    if (!existsSync(file)) continue;
    const have = lf(readFileSync(file, "utf8"));
    if (have === content) continue;
    // Differs from what ships: clean only if it is exactly what a previous install wrote.
    if (rel in manifest && sha256(have) === manifest[rel]) continue;
    throw edited(rel);
  }
  for (const [rel, hash] of Object.entries(manifest)) {
    if (rel in refs || !safeRel(rel)) continue;
    const file = join(target, ...rel.split("/"));
    if (existsSync(file) && sha256(readFileSync(file, "utf8")) !== hash) throw edited(rel);
  }
}

/**
 * @param {string[]} args
 * @param {(s: string) => void} out
 * @param {(s: string) => void} err
 * @returns {number}
 */
export function runInit(args, out, err) {
  const { values } = parseArgs({ args, allowPositionals: false, options: { skill: { type: "boolean", default: false }, force: { type: "boolean", default: false }, cwd: { type: "string" }, "skills-dir": { type: "string" } } });
  if (!values.skill) { err("good-agent: init needs --skill in this version (--config, --hook and --ci come in 0.2)\nUsage: good-agent init --skill [--force]"); return 2; }
  const root = resolve(values.cwd ?? process.cwd());
  let isDir = false;
  try { isDir = statSync(root).isDirectory(); } catch { /* missing */ }
  if (!isDir) { err(`good-agent: ${root} is not a directory`); return 2; }
  try {
    const result = installSkills({ root, skillsDir: values["skills-dir"] ? resolve(values["skills-dir"]) : DEFAULT_SKILLS_DIR, force: values.force });
    for (const p of result.installed) out(`installed ${p}`);
    for (const p of result.unchanged) out(`unchanged ${p}`);
    return 0;
  } catch (error) {
    if (error instanceof InitRefusal) { err(`good-agent: ${error.message}`); return 2; }
    throw error;
  }
}
