// @ts-check
/**
 * `good-agent init --skill [--force]`: install every shipped skill into
 * .agents/skills/<name>/ (Codex, Copilot) and .claude/skills/<name>/ (Claude
 * Code, Copilot) as generated copies. SKILL.md keeps `---` as its first line
 * (the Agent Skills format requires it); the first body line is a marker
 * naming the copy generated, giving the refresh command, and holding a hash
 * of the whole file with that line removed. Files under references/ are
 * hashed into .good-agent-manifest.json beside the installed SKILL.md. A
 * copy whose hash does not match was hand-edited: init refuses to overwrite
 * it (exit 2) unless --force. The source skills directory is a parameter so
 * tests can use a fixture skill.
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { parseFrontMatter } from "./markdown.mjs";

export const DEFAULT_SKILLS_DIR = join(dirname(fileURLToPath(import.meta.url)), "..", "skill");
export const INSTALL_DIRS = [".agents/skills", ".claude/skills"];
export const MANIFEST = ".good-agent-manifest.json";
const REFRESH = "npx good-agent init --skill";
const MARKER_RE = /^<!-- generated by good-agent init --skill; do not edit; refresh with: npx good-agent init --skill; sha256: ([0-9a-f]{64}) -->$/;

export class InitRefusal extends Error {}

/** @param {string} text */
export function sha256(text) {
  return createHash("sha256").update(text).digest("hex");
}

/**
 * The installed SKILL.md text: front matter, marker, body.
 * @param {string} source
 */
export function renderInstalledSkill(source) {
  const fm = parseFrontMatter(source);
  if (!fm) throw new Error("SKILL.md must start with front matter");
  const head = source.slice(0, fm.bodyStart);
  const body = source.slice(fm.bodyStart);
  const hash = sha256(head + body);
  const marker = `<!-- generated by good-agent init --skill; do not edit; refresh with: ${REFRESH}; sha256: ${hash} -->`;
  return `${head}${marker}\n${body}`;
}

/**
 * Whether an installed SKILL.md is an unmodified generated copy. Returns
 * "ok", "missing-marker" or "edited".
 * @param {string} installed
 */
export function installedState(installed) {
  const fm = parseFrontMatter(installed);
  if (!fm) return "missing-marker";
  const markerLine = installed.slice(fm.bodyStart).split("\n")[0] ?? "";
  const m = MARKER_RE.exec(markerLine);
  if (!m) return "missing-marker";
  const without = installed.slice(0, fm.bodyStart) + installed.slice(fm.bodyStart + markerLine.length + 1);
  return sha256(without) === m[1] ? "ok" : "edited";
}

/**
 * @param {string} dir
 * @returns {string[]} files under references/, relative to the skill dir, POSIX
 */
function referenceFiles(dir) {
  const refs = join(dir, "references");
  if (!existsSync(refs)) return [];
  /** @type {string[]} */
  const out = [];
  /** @param {string} d */
  const walk = (d) => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      const abs = join(d, e.name);
      if (e.isDirectory()) walk(abs);
      else if (e.isFile()) out.push(relative(dir, abs).split(sep).join("/"));
    }
  };
  walk(refs);
  return out.sort();
}

/**
 * @param {string} manifestPath
 * @returns {Record<string, string>}
 */
function readManifest(manifestPath) {
  if (!existsSync(manifestPath)) return {};
  try {
    const parsed = JSON.parse(readFileSync(manifestPath, "utf8"));
    if (parsed && typeof parsed === "object" && !Array.isArray(parsed)) return parsed;
  } catch { /* fall through */ }
  throw new InitRefusal(`${manifestPath} is not a valid good-agent manifest; re-run with --force to rewrite it`);
}

/**
 * @param {object} options
 * @param {string} options.root  the target repository
 * @param {string} [options.skillsDir]  the source skills directory
 * @param {boolean} [options.force]
 * @returns {{ installed: string[], unchanged: string[] }}
 */
export function installSkills({ root, skillsDir = DEFAULT_SKILLS_DIR, force = false }) {
  const names = readdirSync(skillsDir, { withFileTypes: true }).filter((e) => e.isDirectory() && existsSync(join(skillsDir, e.name, "SKILL.md"))).map((e) => e.name).sort();
  if (names.length === 0) throw new Error(`no skills found under ${skillsDir}`);
  /** @type {string[]} */
  const installed = [];
  /** @type {string[]} */
  const unchanged = [];
  // First pass: refuse before writing anything if any target was hand-edited.
  /** @type {{ name: string, target: string, skill: string, refs: Record<string, string> }[]} */
  const plan = [];
  for (const name of names) {
    const src = join(skillsDir, name);
    const skill = renderInstalledSkill(readFileSync(join(src, "SKILL.md"), "utf8"));
    /** @type {Record<string, string>} */
    const refs = {};
    for (const rel of referenceFiles(src)) refs[rel] = readFileSync(join(src, ...rel.split("/")), "utf8");
    for (const base of INSTALL_DIRS) {
      const target = join(root, ...base.split("/"), name);
      const existing = join(target, "SKILL.md");
      if (existsSync(existing) && !force) {
        const state = installedState(readFileSync(existing, "utf8"));
        if (state !== "ok") throw new InitRefusal(`${relative(root, existing)} was ${state === "edited" ? "hand-edited" : "not generated by good-agent (no marker)"}; keep your edits in the canonical file or a separate skill, or re-run with --force to overwrite it`);
        const manifestPath = join(target, MANIFEST);
        const manifest = readManifest(manifestPath);
        for (const rel of Object.keys(manifest)) {
          const file = join(target, ...rel.split("/"));
          if (existsSync(file) && sha256(readFileSync(file, "utf8")) !== manifest[rel]) throw new InitRefusal(`${relative(root, file)} was hand-edited; re-run with --force to overwrite it`);
        }
      }
      plan.push({ name, target, skill, refs });
    }
  }
  for (const item of plan) {
    mkdirSync(item.target, { recursive: true });
    const skillPath = join(item.target, "SKILL.md");
    const manifestPath = join(item.target, MANIFEST);
    /** @type {Record<string, string>} */
    const manifest = {};
    let changed = false;
    if (!existsSync(skillPath) || readFileSync(skillPath, "utf8") !== item.skill) { writeFileSync(skillPath, item.skill); changed = true; }
    for (const [rel, content] of Object.entries(item.refs)) {
      const file = join(item.target, ...rel.split("/"));
      mkdirSync(dirname(file), { recursive: true });
      if (!existsSync(file) || readFileSync(file, "utf8") !== content) { writeFileSync(file, content); changed = true; }
      manifest[rel] = sha256(content);
    }
    const manifestText = `${JSON.stringify(manifest, null, 2)}\n`;
    if (Object.keys(manifest).length > 0 && (!existsSync(manifestPath) || readFileSync(manifestPath, "utf8") !== manifestText)) { writeFileSync(manifestPath, manifestText); changed = true; }
    (changed ? installed : unchanged).push(relative(root, item.target).split(sep).join("/"));
  }
  return { installed, unchanged };
}

/**
 * @param {string[]} args
 * @param {(s: string) => void} out
 * @param {(s: string) => void} err
 * @returns {number}
 */
export function runInit(args, out, err) {
  const { values } = parseArgs({ args, allowPositionals: false, options: { skill: { type: "boolean", default: false }, force: { type: "boolean", default: false }, cwd: { type: "string" }, "skills-dir": { type: "string" } } });
  if (!values.skill) { err("good-agent: init needs --skill in this version (--config, --hook and --ci come in 0.2)\nUsage: good-agent init --skill [--force]"); return 2; }
  const root = resolve(values.cwd ?? process.cwd());
  let isDir = false;
  try { isDir = statSync(root).isDirectory(); } catch { /* missing */ }
  if (!isDir) { err(`good-agent: ${root} is not a directory`); return 2; }
  try {
    const result = installSkills({ root, skillsDir: values["skills-dir"] ? resolve(values["skills-dir"]) : DEFAULT_SKILLS_DIR, force: values.force });
    for (const p of result.installed) out(`installed ${p}`);
    for (const p of result.unchanged) out(`unchanged ${p}`);
    return 0;
  } catch (error) {
    if (error instanceof InitRefusal) { err(`good-agent: ${error.message}`); return 2; }
    throw error;
  }
}
