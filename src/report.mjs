// @ts-check
import { VERSION, fileReport } from "./engine.mjs";

const ICON = { error: "✖", warn: "▲", info: "·" };

/**
 * @param {string} text
 * @param {number} width
 * @param {string} indent
 */
function wrap(text, width, indent) {
  const words = text.split(/\s+/);
  /** @type {string[]} */
  const lines = [];
  let line = "";
  for (const w of words) {
    if (line && (line + " " + w).length > width) { lines.push(line); line = w; }
    else line = line ? `${line} ${w}` : w;
  }
  if (line) lines.push(line);
  return lines.map((l) => indent + l).join("\n");
}

/**
 * @param {import("./engine.mjs").Analysis} analysis
 * @param {import("./engine.mjs").ReportedFinding[]} findings
 * @param {{ verbose?: boolean, quiet?: boolean, strict?: boolean, nothingToCheck?: boolean }} options
 */
export function formatHuman(analysis, findings, options) {
  const shown = options.verbose ? findings : findings.filter((f) => f.severity !== "info");
  const errors = findings.filter((f) => f.severity === "error").length;
  const warnings = findings.filter((f) => f.severity === "warn").length;
  const info = findings.filter((f) => f.severity === "info").length;
  const exitCode = errors > 0 || (options.strict && warnings > 0) ? 1 : 0;
  const parts = [];
  const canonical = analysis.canonical.canonical ?? "(none)";
  if (!options.quiet) {
    parts.push(`good-agent ${VERSION} · ${analysis.repo.files.length} instruction file${analysis.repo.files.length === 1 ? "" : "s"} · canonical ${canonical}`);
    parts.push("");
    for (const f of shown) {
      const where = f.line ? `${f.file}:${f.line}` : f.file;
      parts.push(`${ICON[f.severity]} ${where}  ${f.rule}`);
      parts.push(wrap(f.message, 78, "  "));
      if (f.generatedBy) parts.push(`  generated by ${f.generatedBy}; fix the generator, not this file.`);
      parts.push(wrap(`fix: ${f.fix}`, 78, "  "));
      parts.push(`  docs: ${f.docs[0]}`);
      parts.push("");
    }
  }
  const plural = /** @param {number} n @param {string} w */ (n, w) => `${n} ${w}${n === 1 ? "" : "s"}`;
  const tail = [plural(errors, "error"), plural(warnings, "warning")];
  if (info > 0) tail.push(`${info} info${options.verbose ? "" : " (hidden; --verbose shows them)"}`);
  parts.push(`${tail.join(", ")}  (exit ${exitCode})`);
  return parts.join("\n");
}

/**
 * @param {import("./engine.mjs").Analysis} analysis
 * @param {import("./engine.mjs").ReportedFinding[]} findings
 * @param {{ strict?: boolean, configPath: string | null }} options
 */
export function formatJson(analysis, findings, options) {
  const errors = findings.filter((f) => f.severity === "error").length;
  const warnings = findings.filter((f) => f.severity === "warn").length;
  const info = findings.filter((f) => f.severity === "info").length;
  const exitCode = errors > 0 || (options.strict && warnings > 0) ? 1 : 0;
  return JSON.stringify({
    version: VERSION,
    root: analysis.repo.root,
    config: options.configPath,
    canonical: analysis.canonical.canonical,
    files: fileReport(analysis),
    findings: findings.map((f) => ({ rule: f.rule, severity: f.severity, file: f.file, ...(f.line ? { line: f.line } : {}), message: f.message, fix: f.fix, docs: f.docs, ...(f.generatedBy ? { generatedBy: f.generatedBy } : {}), ...(f.data ? { data: f.data } : {}) })),
    summary: { errors, warnings, info, exitCode },
  }, null, 2);
}

/** @param {ReturnType<typeof import("./engine.mjs").inspectData>} data */
export function formatInspect(data) {
  const lines = [];
  lines.push(`good-agent ${data.version} · inspect · ${data.root}`);
  lines.push(`canonical: ${data.canonical ?? "(none)"} (${data.canonicalReason})`);
  lines.push("");
  lines.push("Instruction files");
  for (const f of data.files) lines.push(`  ${String(f.bytes).padStart(7)} B  ${String(f.lines).padStart(5)} lines  ${f.path}  [${f.readBy.join(", ") || "-"}]`);
  lines.push("");
  lines.push(`Codex (limit ${data.codex.limit.toLocaleString("en-US")} bytes per chain)`);
  if (data.codex.chains.length === 0) lines.push("  no AGENTS.md");
  for (const c of data.codex.chains) {
    const over = c.bytes > c.limit ? `  OVER by ${(c.bytes - c.limit).toLocaleString("en-US")}` : "";
    lines.push(`  ${c.dir}: ${c.entries.map((e) => `${e.file} (${e.bytes.toLocaleString("en-US")}${e.shadows ? `, shadows ${e.shadows}` : ""})`).join(" → ")} = ${c.bytes.toLocaleString("en-US")} bytes${over}`);
  }
  lines.push("");
  lines.push(`Claude Code (target ${data.claude.limit} lines per file)`);
  if (data.claude.launch.length === 0) lines.push("  nothing loads at launch");
  for (const e of data.claude.launch) lines.push(`  ${String(e.lines).padStart(5)} lines  ${e.file}${e.via ? `  (via @import in ${e.via})` : data.claude.fallback && e.file === "AGENTS.md" ? "  (fallback: no CLAUDE.md)" : ""}`);
  if (data.claude.launch.length > 1) lines.push(`  ${String(data.claude.lines).padStart(5)} lines  in all`);
  lines.push("");
  lines.push("Copilot");
  lines.push(`  repo-wide: ${data.copilot.repoWide ?? "(none)"}`);
  for (const p of data.copilot.pathSpecific) lines.push(`  ${p.file}  applyTo: ${p.applyTo ?? "(missing)"}`);
  return lines.join("\n");
}
