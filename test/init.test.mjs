// @ts-check
import { test } from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { existsSync, lstatSync, mkdirSync, readdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { run, FIXTURES, REPO, tempTree } from "./helpers.mjs";
import { parseFrontMatter } from "../src/markdown.mjs";
import { validateSkillFile } from "../src/skill-validate.mjs";

const SKILLS = join(FIXTURES, "skills", "valid");
const COPIES = [".agents/skills/good-skill", ".claude/skills/good-skill"];

/** @returns {{ root: string, cleanup: () => void }} */
function scratch() {
  const root = mkdtempSync(join(tmpdir(), "good-agent-init-"));
  return { root, cleanup: () => rmSync(root, { recursive: true, force: true }) };
}

/** @param {string} root @param {string[]} [extra] */
function init(root, extra = []) {
  return run(["init", "--skill", "--cwd", root, "--skills-dir", SKILLS, ...extra]);
}

/** @param {string} root @param {string} copy @param {string} rel */
const path = (root, copy, rel) => join(root, ...copy.split("/"), ...rel.split("/"));

/** Run `body` against a freshly installed fixture repo. @param {(root: string) => void} body */
function withInstalled(body) {
  const t = scratch();
  try {
    assert.equal(init(t.root).status, 0);
    body(t.root);
  } finally { t.cleanup(); }
}

/** @param {string} root @param {string} copy @param {string} rel @param {(text: string) => string} mutate */
function editFile(root, copy, rel, mutate) {
  const file = path(root, copy, rel);
  writeFileSync(file, mutate(readFileSync(file, "utf8")));
}

test("init --skill creates both copies with the marker on the first body line and a manifest", () => {
  withInstalled((root) => {
    for (const copy of COPIES) {
      const text = readFileSync(path(root, copy, "SKILL.md"), "utf8");
      assert.ok(text.startsWith("---\n"), `${copy}: --- must be line 1`);
      const fm = parseFrontMatter(text);
      assert.ok(fm);
      const firstBodyLine = text.slice(fm.bodyStart).split("\n")[0];
      assert.match(firstBodyLine, /^<!-- generated by good-agent init --skill; do not edit; refresh with: npx good-agent init --skill; sha256: [0-9a-f]{64} -->$/);
      assert.ok(existsSync(path(root, copy, "references/note.md")));
      const manifest = JSON.parse(readFileSync(path(root, copy, ".good-agent-manifest.json"), "utf8"));
      assert.deepEqual(Object.keys(manifest), ["references/note.md"]);
      assert.match(manifest["references/note.md"], /^[0-9a-f]{64}$/);
    }
  });
});

test("a second run prints unchanged and leaves every byte alone", () => {
  const t = scratch();
  try {
    const first = init(t.root);
    assert.equal(first.status, 0);
    assert.match(first.stdout, /installed \.agents\/skills\/good-skill/);
    const before = COPIES.map((c) => readFileSync(path(t.root, c, "SKILL.md"), "utf8"));
    const second = init(t.root);
    assert.equal(second.status, 0);
    assert.match(second.stdout, /unchanged \.agents\/skills\/good-skill/);
    assert.match(second.stdout, /unchanged \.claude\/skills\/good-skill/);
    assert.doesNotMatch(second.stdout, /installed/);
    assert.deepEqual(COPIES.map((c) => readFileSync(path(t.root, c, "SKILL.md"), "utf8")), before);
  } finally { t.cleanup(); }
});

/** @type {Record<string, { file: string, mutate: (text: string) => string }>} */
const EDITS = {
  "body edit": { file: "SKILL.md", mutate: (t) => `${t}\nAn extra rule.\n` },
  "front-matter-only edit": { file: "SKILL.md", mutate: (t) => t.replace("A valid fixture skill", "An edited fixture skill") },
  "reference-file edit": { file: "references/note.md", mutate: (t) => `${t}Edited.\n` },
  "copy without the marker": { file: "SKILL.md", mutate: (t) => t.replace(/^<!-- generated by .* -->\n/m, "") },
};

for (const [label, { file, mutate }] of Object.entries(EDITS)) {
  test(`${label}: init refuses with exit 2 naming the file, and --force overwrites it`, () => {
    withInstalled((root) => {
      const edited = COPIES[1];
      editFile(root, edited, file, mutate);
      const changed = readFileSync(path(root, edited, file), "utf8");
      const refused = init(root);
      assert.equal(refused.status, 2, refused.stderr);
      assert.ok(refused.stderr.includes(`.claude/skills/good-skill/${file}`), refused.stderr);
      assert.equal(readFileSync(path(root, edited, file), "utf8"), changed, "the edited copy is left as it was");
      const forced = init(root, ["--force"]);
      assert.equal(forced.status, 0, forced.stderr);
      assert.notEqual(readFileSync(path(root, edited, file), "utf8"), changed);
      assert.equal(init(root).status, 0, "the repaired copy is clean again");
    });
  });
}

test("a refusal writes nothing: an unedited copy is not refreshed ahead of an edited one", () => {
  const t = scratch();
  try {
    assert.equal(init(t.root).status, 0);
    editFile(t.root, COPIES[1], "SKILL.md", (x) => `${x}\nEdited.\n`);
    rmSync(path(t.root, COPIES[0], "references/note.md"));
    assert.equal(init(t.root).status, 2);
    assert.equal(existsSync(path(t.root, COPIES[0], "references/note.md")), false);
  } finally { t.cleanup(); }
});

test("--config, --hook and --ci are unknown flags in this version: exit 2 and a usage message", () => {
  const t = scratch();
  try {
    for (const flag of ["--config", "--hook", "--ci"]) {
      const r = run(["init", "--skill", flag, "--cwd", t.root, "--skills-dir", SKILLS]);
      assert.equal(r.status, 2, flag);
      assert.match(r.stderr, /Unknown option/i, flag);
      assert.doesNotMatch(r.stderr, /internal error|at .*\.mjs/, flag);
    }
    const bare = run(["init", "--cwd", t.root]);
    assert.equal(bare.status, 2);
    assert.match(bare.stderr, /--skill/);
    assert.equal(existsSync(join(t.root, ".agents")), false);
  } finally { t.cleanup(); }
});

test("a CRLF checkout of unedited copies is not an edit: the next run is unchanged", () => {
  withInstalled((root) => {
    const files = COPIES.flatMap((c) => ["SKILL.md", "references/note.md", ".good-agent-manifest.json"].map((f) => path(root, c, f)));
    for (const f of files) writeFileSync(f, readFileSync(f, "utf8").replace(/\n/g, "\r\n"));
    const r = init(root);
    assert.equal(r.status, 0, r.stderr);
    assert.match(r.stdout, /unchanged \.agents\/skills\/good-skill/);
    assert.match(r.stdout, /unchanged \.claude\/skills\/good-skill/);
    assert.ok(readFileSync(files[0], "utf8").includes("\r\n"), "line endings are left alone");
    // A real edit is still caught in a CRLF file.
    writeFileSync(files[1], readFileSync(files[1], "utf8").replace(/\r\n/g, "\n").replace(/\n/g, "\r\n") + "Edited.\r\n");
    assert.equal(init(root).status, 2);
  });
});

test("an edited reference is still refused when the manifest is gone, and an unedited one is not", () => {
  withInstalled((root) => {
    for (const c of COPIES) rmSync(path(root, c, ".good-agent-manifest.json"));
    const clean = init(root);
    assert.equal(clean.status, 0, clean.stderr);
    assert.ok(existsSync(path(root, COPIES[0], ".good-agent-manifest.json")), "the manifest is rewritten");
    rmSync(path(root, COPIES[1], ".good-agent-manifest.json"));
    editFile(root, COPIES[1], "references/note.md", (x) => `${x}Edited.\n`);
    const refused = init(root);
    assert.equal(refused.status, 2);
    assert.ok(refused.stderr.includes(".claude/skills/good-skill/references/note.md"), refused.stderr);
    assert.equal(init(root, ["--force"]).status, 0);
  });
});

test("references that a skill drops or renames are reconciled, and the manifest follows", () => {
  const skill = (/** @type {Record<string, string>} */ refs) => ({
    "good-skill/SKILL.md": "---\nname: good-skill\ndescription: A fixture skill.\n---\n\n# Body\n",
    ...Object.fromEntries(Object.entries(refs).map(([k, v]) => [`good-skill/references/${k}`, v])),
  });
  const first = tempTree(skill({ "a.md": "A\n", "b.md": "B\n" }));
  const second = tempTree(skill({ "a.md": "A\n", "c.md": "C\n" }));
  const third = tempTree(skill({}));
  const target = scratch();
  const install = (/** @type {string} */ dir, extra = /** @type {string[]} */ ([])) => run(["init", "--skill", "--cwd", target.root, "--skills-dir", dir, ...extra]);
  try {
    assert.equal(install(first.root).status, 0);
    assert.equal(install(second.root).status, 0);
    for (const c of COPIES) {
      assert.equal(existsSync(path(target.root, c, "references/b.md")), false, "the dropped reference is removed");
      assert.ok(existsSync(path(target.root, c, "references/c.md")));
      assert.deepEqual(Object.keys(JSON.parse(readFileSync(path(target.root, c, ".good-agent-manifest.json"), "utf8"))), ["references/a.md", "references/c.md"]);
    }
    // An edited orphan is refused without --force and removed with it.
    assert.equal(install(first.root).status, 0);
    editFile(target.root, COPIES[0], "references/b.md", (x) => `${x}Edited.\n`);
    const refused = install(second.root);
    assert.equal(refused.status, 2);
    assert.ok(refused.stderr.includes(".agents/skills/good-skill/references/b.md"), refused.stderr);
    assert.equal(install(second.root, ["--force"]).status, 0);
    assert.equal(existsSync(path(target.root, COPIES[0], "references/b.md")), false);
    // No references left: the manifest and the folder go.
    assert.equal(install(third.root).status, 0);
    for (const c of COPIES) {
      assert.equal(existsSync(path(target.root, c, ".good-agent-manifest.json")), false);
      assert.equal(existsSync(path(target.root, c, "references")), false);
    }
  } finally { first.cleanup(); second.cleanup(); third.cleanup(); target.cleanup(); }
});

test("a regular file where a skill directory should be is refused up front: exit 2 naming it, nothing written", () => {
  const t = scratch();
  try {
    mkdirSync(join(t.root, ".claude", "skills"), { recursive: true });
    writeFileSync(join(t.root, ".claude", "skills", "good-skill"), "in the way\n");
    for (const extra of [[], ["--force"]]) {
      const r = init(t.root, extra);
      assert.equal(r.status, 2, r.stderr);
      assert.ok(r.stderr.includes(".claude/skills/good-skill"), r.stderr);
      assert.doesNotMatch(r.stderr, /internal error/);
      assert.equal(existsSync(join(t.root, ".agents")), false, "the other copy is not written either");
    }
    assert.equal(readFileSync(join(t.root, ".claude", "skills", "good-skill"), "utf8"), "in the way\n");
  } finally { t.cleanup(); }
});

test("a file where the skills root or a reference parent should be is refused too", () => {
  const t = scratch();
  try {
    mkdirSync(join(t.root, ".agents"), { recursive: true });
    writeFileSync(join(t.root, ".agents", "skills"), "x\n");
    const r = init(t.root);
    assert.equal(r.status, 2);
    assert.ok(r.stderr.includes(".agents/skills"), r.stderr);
  } finally { t.cleanup(); }
  withInstalled((root) => {
    rmSync(path(root, COPIES[1], "references"), { recursive: true });
    writeFileSync(path(root, COPIES[1], "references"), "x\n");
    const r = init(root, ["--force"]);
    assert.equal(r.status, 2);
    assert.ok(r.stderr.includes(".claude/skills/good-skill/references"), r.stderr);
  });
});

test("a symlinked destination is refused even with --force, and nothing is written through it", () => {
  for (const what of ["dir", "skill", "manifest", "reference"]) {
    const t = scratch();
    const elsewhere = scratch();
    try {
      assert.equal(init(t.root).status, 0);
      const copy = path(t.root, COPIES[1], "");
      writeFileSync(join(elsewhere.root, "other.md"), "other\n");
      const victim = { dir: copy.replace(/\/$/, ""), skill: path(t.root, COPIES[1], "SKILL.md"), manifest: path(t.root, COPIES[1], ".good-agent-manifest.json"), reference: path(t.root, COPIES[1], "references/note.md") }[what];
      assert.ok(victim);
      rmSync(victim, { recursive: true });
      if (what === "dir") { mkdirSync(join(elsewhere.root, "real")); symlinkSync(join(elsewhere.root, "real"), victim); } else symlinkSync(join(elsewhere.root, "other.md"), victim);
      for (const extra of [[], ["--force"]]) {
        const r = init(t.root, extra);
        assert.equal(r.status, 2, `${what}: ${r.stderr}`);
        assert.match(r.stderr, /symbolic link/);
        assert.ok(r.stderr.includes(".claude/skills/good-skill"), r.stderr);
      }
      assert.ok(lstatSync(victim).isSymbolicLink());
      assert.equal(readFileSync(join(elsewhere.root, "other.md"), "utf8"), "other\n");
      assert.deepEqual(what === "dir" ? readdirSync(join(elsewhere.root, "real")) : [], []);
    } finally { t.cleanup(); elsewhere.cleanup(); }
  }
});

test("an obsolete reference replaced by a directory or a symlink is a refusal, not a crash", () => {
  const skill = (/** @type {Record<string, string>} */ refs) => ({
    "good-skill/SKILL.md": "---\nname: good-skill\ndescription: A fixture skill.\n---\n\n# Body\n",
    ...Object.fromEntries(Object.entries(refs).map(([k, v]) => [`good-skill/references/${k}`, v])),
  });
  for (const kind of ["dir", "symlink"]) {
    const first = tempTree(skill({ "a.md": "A\n", "b.md": "B\n" }));
    const second = tempTree(skill({ "a.md": "A\n" }));
    const target = scratch();
    const install = (/** @type {string} */ dir, extra = /** @type {string[]} */ ([])) => run(["init", "--skill", "--cwd", target.root, "--skills-dir", dir, ...extra]);
    try {
      assert.equal(install(first.root).status, 0);
      const obsolete = path(target.root, COPIES[0], "references/b.md");
      rmSync(obsolete);
      if (kind === "dir") mkdirSync(obsolete); else symlinkSync(join(first.root, "good-skill", "SKILL.md"), obsolete);
      for (const extra of [[], ["--force"]]) {
        const r = install(second.root, extra);
        assert.equal(r.status, 2, `${kind}: ${r.stderr}`);
        assert.doesNotMatch(r.stderr, /internal error/);
        assert.ok(r.stderr.includes(".agents/skills/good-skill/references/b.md"), r.stderr);
      }
    } finally { first.cleanup(); second.cleanup(); target.cleanup(); }
  }
});

