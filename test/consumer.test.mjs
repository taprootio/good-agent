// @ts-check
import { test } from "node:test";
import assert from "node:assert/strict";
import { existsSync, readFileSync, readdirSync } from "node:fs";
import { dirname, join, resolve, relative, sep } from "node:path";
import { run, tempTree } from "./helpers.mjs";
import { markdownLinks, parseFrontMatter } from "../src/markdown.mjs";
import { validateSkillFile } from "../src/skill-validate.mjs";

/**
 * A consumer repository has only the installed copies: no skill/ tree from
 * this repository. Everything a skill names must resolve inside its own
 * installed directory.
 */
test("consumer fixture: installed skills keep their marker and every relative link resolves", () => {
  const tree = tempTree({ "AGENTS.md": "# Consumer\n" });
  try {
    const r = run(["init", "--skill", "--cwd", tree.root]);
    assert.equal(r.status, 0, r.stderr);
    let checked = 0;
    for (const base of [".agents/skills", ".claude/skills"]) {
      const baseDir = join(tree.root, ...base.split("/"));
      const names = readdirSync(baseDir, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name);
      assert.deepEqual(names.sort(), ["good-agent", "open-pr", "review-loop", "work-task", "write-task"]);
      for (const name of names) {
        const skillDir = join(baseDir, name);
        const file = join(skillDir, "SKILL.md");
        const text = readFileSync(file, "utf8");
        assert.ok(text.startsWith("---\n"), `${base}/${name}: first line must be ---`);
        assert.deepEqual(validateSkillFile(file), [], `${base}/${name}: skill validator`);
        const fm = parseFrontMatter(text);
        assert.ok(fm, `${base}/${name}: front matter`);
        assert.match(text.slice(fm.bodyStart).split("\n")[0], /^<!-- generated by good-agent init --skill;/, `${base}/${name}: marker on the first body line`);
        for (const link of markdownLinks(text)) {
          const target = link.target.split("#")[0];
          if (!target || /^[a-z][a-z0-9+.-]*:/i.test(target) || target.startsWith("/")) continue;
          const abs = resolve(dirname(file), target);
          assert.ok(!relative(skillDir, abs).startsWith(".."), `${base}/${name}: ${target} leaves the skill directory`);
          assert.ok(existsSync(abs), `${base}/${name}: ${target} does not exist (${relative(tree.root, abs).split(sep).join("/")})`);
          checked += 1;
        }
      }
    }
    assert.ok(checked >= 8, `expected the review-loop prompt links in both copies, saw ${checked} links`);
    // Every prompt the other skills name by code span resolves against the
    // installed review-loop directory, in both install roots.
    for (const base of [".agents/skills", ".claude/skills"]) {
      const loopDir = join(tree.root, ...base.split("/"), "review-loop");
      for (const name of ["work-task", "write-task"]) {
        const text = readFileSync(join(tree.root, ...base.split("/"), name, "SKILL.md"), "utf8");
        const named = [...text.matchAll(/`(references\/review-[a-z]+\.md)`/g)].map((m) => m[1]);
        assert.ok(named.length > 0, `${base}/${name} names no review prompt`);
        for (const rel of named) assert.ok(existsSync(join(loopDir, ...rel.split("/"))), `${base}/${name}: ${rel} does not resolve in review-loop`);
      }
      for (const prompt of ["diff", "story", "plan", "design"]) {
        const ref = readFileSync(join(loopDir, "references", `review-${prompt}.md`), "utf8");
        for (const marker of ["<!-- ENDING: manual -->", "<!-- ENDING: runner -->", "<!-- END ENDING -->"]) assert.ok(ref.includes(marker), `${base}: review-${prompt}.md lacks ${marker}`);
      }
    }
  } finally { tree.cleanup(); }
});
